create or replace function public.is_admin(uid uuid default auth.uid()) returns boolean
language sql stable security definer set search_path = public
as $$ select exists(select 1 from public.profiles p where p.id = uid and p.role = 'admin'); $$;

-- Profiles
 drop policy if exists "profile own read" on public.profiles;
 create policy "profile own read" on public.profiles for select using (id = auth.uid() or public.is_admin());
 drop policy if exists "profile insert own" on public.profiles;
 create policy "profile insert own" on public.profiles for insert with check (id = auth.uid() and role = 'user');
 drop policy if exists "profile admin update" on public.profiles;
 create policy "profile admin update" on public.profiles for update using (public.is_admin()) with check (public.is_admin());

-- Issues: users can read/delete only their own; admins can read/update/delete all.
 drop policy if exists "issue own read" on public.issues;
 create policy "issue own read" on public.issues for select using (user_id = auth.uid() or public.is_admin());
 drop policy if exists "issue own insert" on public.issues;
 create policy "issue own insert" on public.issues for insert with check (user_id = auth.uid());
 drop policy if exists "issue admin update" on public.issues;
 create policy "issue admin update" on public.issues for update using (public.is_admin()) with check (public.is_admin());
 drop policy if exists "issue own delete" on public.issues;
 create policy "issue own delete" on public.issues for delete using (user_id = auth.uid() or public.is_admin());

-- Owners can reopen closed issues, but may not edit any other issue fields.
create or replace function public.guard_owner_issue_reopen()
returns trigger
language plpgsql
security definer
set search_path = public
as $g57_guard$
begin
  -- Scheduled SQL runs without an auth.uid(); allow only trusted database roles.
  if auth.uid() is null then
    if current_user in ('postgres', 'service_role', 'supabase_admin') then
      return new;
    end if;
    raise exception 'A signed-in owner or administrator is required.';
  end if;

  if public.is_admin() then
    return new;
  end if;

  if old.user_id is distinct from auth.uid()
     or old.status <> 'closed'
     or new.status <> 'open'
     or (to_jsonb(new) - 'status') is distinct from (to_jsonb(old) - 'status') then
    raise exception 'Users may only reopen their own closed issue.';
  end if;
  return new;
end;
$g57_guard$;drop trigger if exists guard_owner_issue_reopen_trigger on public.issues;
create trigger guard_owner_issue_reopen_trigger
before update on public.issues
for each row execute procedure public.guard_owner_issue_reopen();

drop policy if exists "issue owner reopen closed" on public.issues;
create policy "issue owner reopen closed"
on public.issues for update
using (user_id = auth.uid() and status = 'closed')
with check (user_id = auth.uid() and status = 'open');

-- Attachments: owner/admin read; owner insert; owner/admin delete.
 drop policy if exists "attachment read" on public.attachments;
 create policy "attachment read" on public.attachments for select using (
   exists(select 1 from public.issues i where i.id = issue_id and (i.user_id = auth.uid() or public.is_admin()))
 );
 drop policy if exists "attachment insert" on public.attachments;
 create policy "attachment insert" on public.attachments for insert with check (
   exists(select 1 from public.issues i where i.id = issue_id and i.user_id = auth.uid())
 );
 drop policy if exists "attachment delete" on public.attachments;
 create policy "attachment delete" on public.attachments for delete using (
   exists(select 1 from public.issues i where i.id = issue_id and (i.user_id = auth.uid() or public.is_admin()))
 );

-- Notifications: users see/update their own; admins may see all if needed.
 drop policy if exists "notification own read" on public.notifications;
 create policy "notification own read" on public.notifications for select using (user_id = auth.uid() or public.is_admin());
 drop policy if exists "notification own update" on public.notifications;
 create policy "notification own update" on public.notifications for update using (user_id = auth.uid() or public.is_admin()) with check (user_id = auth.uid() or public.is_admin());

